using System.Text;
using Lapis.Projects;

namespace Lapis.Editor.Scripting;

/// <summary>
/// Files that make a game project's scripts work in an external code editor: a generated
/// <c>.csproj</c> and a copy of the engine assembly with its documentation.
/// </summary>
internal static class ScriptProjectFiles
{
    /// <summary>Every <c>.cs</c> file under the project's <c>Assets</c> folder.</summary>
    public static List<string> FindScripts(LapisProject project)
    {
        if (!Directory.Exists(project.AssetsDirectory))
        {
            return [];
        }

        return [.. Directory.EnumerateFiles(project.AssetsDirectory, "*.cs", SearchOption.AllDirectories)
            .Order(StringComparer.OrdinalIgnoreCase)];
    }

    /// <summary>
    /// Writes <c>{Name}.csproj</c> and copies <c>Lapis.dll</c> / <c>Lapis.xml</c> into <c>.lapis/Engine</c>,
    /// so VS Code offers code completion and documentation for the engine API.
    /// </summary>
    public static void Update(LapisProject project)
    {
        var engineDirectory = Path.Combine(project.CacheDirectory, "Engine");
        Directory.CreateDirectory(engineDirectory);

        var engineAssembly = ScriptCompiler.EngineAssemblyPath;
        CopyIfChanged(engineAssembly, Path.Combine(engineDirectory, "Lapis.dll"));
        CopyIfChanged(Path.ChangeExtension(engineAssembly, ".xml"), Path.Combine(engineDirectory, "Lapis.xml"));

        WriteIfChanged(Path.Combine(project.Directory, project.Name + ".csproj"), CreateProjectFile());
    }

    /// <summary>Source code of a new, empty script.</summary>
    public static string NewScript(string className) => $$"""
        /// <summary>Describe what this script does.</summary>
        public class {{className}} : Behaviour
        {
            public override void Start()
            {
            }

            public override void Update()
            {
            }
        }

        """;

    /// <summary>True when <paramref name="name"/> can be used as a C# class name.</summary>
    public static bool IsValidClassName(string name) =>
        name.Length > 0 && (char.IsLetter(name[0]) || name[0] == '_') && name.All(c => char.IsLetterOrDigit(c) || c == '_') &&
        Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) == Microsoft.CodeAnalysis.CSharp.SyntaxKind.None;

    private static string CreateProjectFile()
    {
        var usings = new StringBuilder();
        foreach (var ns in ScriptCompiler.GlobalUsings)
        {
            usings.Append("    <Using Include=\"").Append(ns).Append("\" />\n");
        }

        return $"""
            <Project>
              <!--
                Generated by the Lapis editor; changes are overwritten.
                It only exists so code editors can offer completion and errors.
                The editor compiles the scripts itself, so building this project is not needed.
              -->
              <PropertyGroup>
                <ImportDirectoryBuildProps>false</ImportDirectoryBuildProps>
                <ImportDirectoryBuildTargets>false</ImportDirectoryBuildTargets>
                <ImportDirectoryPackagesProps>false</ImportDirectoryPackagesProps>
                <BaseIntermediateOutputPath>.lapis\obj\</BaseIntermediateOutputPath>
                <BaseOutputPath>.lapis\bin\</BaseOutputPath>
              </PropertyGroup>

              <Import Project="Sdk.props" Sdk="Microsoft.NET.Sdk" />

              <PropertyGroup>
                <TargetFramework>net10.0</TargetFramework>
                <AssemblyName>{ScriptCompiler.AssemblyName}</AssemblyName>
                <Nullable>annotations</Nullable>
                <ImplicitUsings>disable</ImplicitUsings>
                <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
              </PropertyGroup>

              <ItemGroup>
                <Compile Include="Assets\**\*.cs" />
                <Reference Include="Lapis">
                  <HintPath>.lapis\Engine\Lapis.dll</HintPath>
                </Reference>
            {usings}  </ItemGroup>

              <Import Project="Sdk.targets" Sdk="Microsoft.NET.Sdk" />
            </Project>

            """;
    }

    private static void CopyIfChanged(string source, string destination)
    {
        if (!File.Exists(source))
        {
            return;
        }

        var sourceInfo = new FileInfo(source);
        var destinationInfo = new FileInfo(destination);
        if (destinationInfo.Exists && destinationInfo.Length == sourceInfo.Length && destinationInfo.LastWriteTimeUtc >= sourceInfo.LastWriteTimeUtc)
        {
            return;
        }

        File.Copy(source, destination, overwrite: true);
    }

    private static void WriteIfChanged(string path, string content)
    {
        if (File.Exists(path) && File.ReadAllText(path) == content)
        {
            return;
        }

        File.WriteAllText(path, content);
    }
}
